/// Emits idempotent upsert SQL for the import.
///
/// Everything is written as `INSERT ... ON CONFLICT ... DO UPDATE`, so the same
/// file can be applied twice and the second application updates rather than
/// duplicates. That is what makes the import safe to re-run while mapping
/// rules are still being tuned.
///
/// Conflict targets:
///   * depots         - code, then a case-insensitive name match
///   * routine_tasks  - title
///   * trucks         - reg_no
///
/// Depots are emitted first so that children can resolve their ids.
library;

import 'dart:convert';

import 'mapping.dart';

/// Escapes a literal for a PostgreSQL single-quoted string.
String lit(Object? value) {
  if (value == null) return 'NULL';
  final s = value is String ? value : value.toString();
  return "'${s.replaceAll("'", "''")}'";
}

/// Emits a JSONB literal.
String jsonLit(Map<String, dynamic> value) =>
    "'${jsonEncode(value).replaceAll("'", "''")}'::jsonb";

abstract final class DepotSql {
  static String build(List<DepotMapping> depots) {
    final b = StringBuffer()
      ..writeln('-- Base44 depots - idempotent upsert')
      ..writeln('-- Generated by tool/import_base44/import.dart')
      ..writeln('begin;')
      ..writeln();

    for (final d in depots) {
      b.writeln('''
insert into public.depots (code, name, city, latitude, longitude, is_active, source_meta)
values (
  ${lit(d.code)},
  ${lit(d.name)},
  ${lit(_cityOf(d.meta))},
  ${d.latitude?.toString() ?? 'NULL'},
  ${d.longitude?.toString() ?? 'NULL'},
  ${d.isActive},
  ${jsonLit(d.meta)}
)
on conflict (code) do update set
  name = excluded.name,
  latitude = coalesce(excluded.latitude, public.depots.latitude),
  longitude = coalesce(excluded.longitude, public.depots.longitude),
  is_active = excluded.is_active,
  source_meta = excluded.source_meta;''');

      // Name fallback: a depot created by the UI with a different code.
      b.writeln('''
-- ${d.name}: align on name when it exists under a different code
update public.depots set
  latitude = coalesce(${d.latitude?.toString() ?? 'NULL'}, public.depots.latitude),
  longitude = coalesce(${d.longitude?.toString() ?? 'NULL'}, public.depots.longitude),
  is_active = ${d.isActive}
where btrim(upper(name)) = btrim(upper(${lit(d.name)}))
  and code <> ${lit(d.code)};''');
    }

    b.writeln('commit;');
    return b.toString();
  }

  /// The export's `city` column is usually blank, with the place in `name`.
  static String? _cityOf(Map<String, dynamic> meta) {
    final city = (meta['city'] as String?)?.trim();
    if (city != null && city.isNotEmpty) return city;
    final name = (meta['name'] as String?)?.trim();
    return (name != null && name.isNotEmpty) ? name : null;
  }
}

abstract final class TaskSql {
  static String build(List<TaskMapping> tasks) {
    final b = StringBuffer()
      ..writeln('-- Base44 routine tasks - idempotent upsert')
      ..writeln('-- Generated by tool/import_base44/import.dart')
      ..writeln('begin;')
      ..writeln();

    for (final t in tasks) {
      // Depots arrive as names, resolved to UUIDs here. `all_depots` short-
      // circuits to an empty array so the task applies everywhere.
      final depotSelects = t.allDepots
          ? const <String>['NULL']
          : t.assignedDepotNames
                .map(
                  (n) =>
                      '(select id from public.depots where btrim(upper(name)) = btrim(upper(${lit(n)})) limit 1)',
                )
                .toList();

      b.writeln('''
-- ${t.title}
insert into public.routine_tasks (
  title, description, task_type, category, all_depots, assigned_depot_ids,
  frequency, linked_module, requires_photo_on_completion,
  monthly_dates, start_date, is_active, source_meta
)
values (
  ${lit(t.title)},
  ${lit(t.description)},
  ${lit(t.taskType)}::completion_method,
  ${t.category == null ? 'NULL' : lit(t.category)},
  ${t.allDepots},
  coalesce(array(
    select x::uuid from unnest(array[${depotSelects.join(', ')}]) as x
    where x is not null
  ), '{}'),
  ${lit(t.frequency)}::frequency,
  ${t.linkedModule == null ? 'NULL' : lit(t.linkedModule)},
  ${t.requiresPhoto},
  '{1}',
  current_date,
  true,
  ${jsonLit(t.meta)}
)
on conflict (title) do update set
  description = excluded.description,
  task_type = excluded.task_type,
  category = excluded.category,
  all_depots = excluded.all_depots,
  assigned_depot_ids = excluded.assigned_depot_ids,
  frequency = excluded.frequency,
  linked_module = excluded.linked_module,
  requires_photo_on_completion = excluded.requires_photo_on_completion,
  is_active = true,
  source_meta = excluded.source_meta;''');
    }

    b.writeln('commit;');
    return b.toString();
  }
}

abstract final class TruckSql {
  static String build(List<TruckMapping> trucks) {
    final b = StringBuffer()
      ..writeln('-- Base44 vehicles - idempotent upsert onto public.trucks')
      ..writeln('-- Generated by tool/import_base44/import.dart')
      ..writeln('begin;')
      ..writeln();

    for (final t in trucks) {
      b.writeln('''
-- ${t.regNo}
insert into public.trucks (
  reg_no, depot_id, company, driver_name, driver_phone, make_model, year,
  status, color, qr_code_url, last_inspection_date, last_inspection_result,
  next_inspection_date, is_active, source_meta
)
values (
  ${lit(t.regNo)},
  (select id from public.depots where btrim(upper(name)) = btrim(upper(${lit(t.depotName)})) limit 1),
  ${t.company == null ? 'NULL' : lit(t.company)},
  ${t.driverName == null ? 'NULL' : lit(t.driverName)},
  ${t.driverPhone == null ? 'NULL' : lit(t.driverPhone)},
  ${t.makeModel == null ? 'NULL' : lit(t.makeModel)},
  ${t.year?.toString() ?? 'NULL'},
  ${lit(t.status)},
  ${t.color == null ? 'NULL' : lit(t.color)},
  ${t.qrCodeUrl == null ? 'NULL' : lit(t.qrCodeUrl)},
  ${t.lastInspectionDate == null ? 'NULL' : "${lit(t.lastInspectionDate!)}::date"},
  ${t.lastInspectionResult == null ? 'NULL' : lit(t.lastInspectionResult)},
  ${t.nextInspectionDate == null ? 'NULL' : "${lit(t.nextInspectionDate!)}::date"},
  true,
  ${jsonLit(t.meta)}
)
on conflict (reg_no) do update set
  depot_id = coalesce(excluded.depot_id, public.trucks.depot_id),
  company = coalesce(excluded.company, public.trucks.company),
  driver_name = coalesce(excluded.driver_name, public.trucks.driver_name),
  driver_phone = coalesce(excluded.driver_phone, public.trucks.driver_phone),
  make_model = coalesce(excluded.make_model, public.trucks.make_model),
  year = coalesce(excluded.year, public.trucks.year),
  status = excluded.status,
  color = coalesce(excluded.color, public.trucks.color),
  qr_code_url = coalesce(excluded.qr_code_url, public.trucks.qr_code_url),
  last_inspection_date = coalesce(excluded.last_inspection_date, public.trucks.last_inspection_date),
  last_inspection_result = coalesce(excluded.last_inspection_result, public.trucks.last_inspection_result),
  next_inspection_date = coalesce(excluded.next_inspection_date, public.trucks.next_inspection_date),
  is_active = true,
  source_meta = excluded.source_meta;''');
    }

    b.writeln('commit;');
    return b.toString();
  }
}
