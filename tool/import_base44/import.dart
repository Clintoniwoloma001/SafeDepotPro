/// Imports Base44 exports into the Supabase schema.
///
/// Usage:
///   dart run tool/import_base44/import.dart --input DIR --out build/import
///
/// Emits an idempotent SQL file (`build/import/base44.sql`) that upserts by
/// business key — depot code then depot name, routine-task title, truck number.
/// Re-running against the same exports produces the same rows and updates
/// rather than duplicates, so this is safe to run more than once.
///
/// It deliberately writes SQL instead of connecting directly: the tool stays
/// free of any database dependency, and the SQL it emits can be read and
/// reviewed before it is applied.
library;

import 'dart:io';

import 'src/csv.dart';
import 'src/mapping.dart';
import 'src/sql.dart';

Future<void> main(List<String> args) async {
  final input = _value(args, '--input') ?? '~/Downloads';
  final out = _value(args, '--out') ?? 'build/import';

  final dir = Directory(_expand(input));
  if (!dir.existsSync()) {
    stderr.writeln('Input directory not found: ${dir.path}');
    exit(2);
  }

  final outDir = Directory(out)..createSync(recursive: true);
  final report = <String, int>{};

  // ---- depots -------------------------------------------------------------
  final depotFile = _find(dir, const ['Depot_export.csv']);
  if (depotFile != null) {
    final rows = CsvReader.read(depotFile);
    final mapped = rows.map(DepotMapping.fromRow).whereType<DepotMapping>();
    final sql = DepotSql.build(mapped.toList(growable: false));
    _write(outDir, 'depots.sql', sql);
    report['depots'] = mapped.length;
  } else {
    report['depots'] = 0;
  }

  // ---- routine tasks ------------------------------------------------------
  final taskFile = _find(dir, const ['RoutineTask_export.csv']);
  if (taskFile != null) {
    final rows = CsvReader.read(taskFile);
    final mapped = rows.map(TaskMapping.fromRow).whereType<TaskMapping>();
    final sql = TaskSql.build(mapped.toList(growable: false));
    _write(outDir, 'routine_tasks.sql', sql);
    report['routine_tasks'] = mapped.length;
  } else {
    report['routine_tasks'] = 0;
  }

  // ---- trucks -------------------------------------------------------------
  final vehicleFile = _find(dir, const ['Vehicle_export.csv']);
  if (vehicleFile != null) {
    final rows = CsvReader.read(vehicleFile);
    final mapped = rows.map(TruckMapping.fromRow).whereType<TruckMapping>();
    final sql = TruckSql.build(mapped.toList(growable: false));
    _write(outDir, 'trucks.sql', sql);
    report['trucks'] = mapped.length;
  } else {
    report['trucks'] = 0;
  }

  // ---- combined file ------------------------------------------------------
  final combined = StringBuffer()
    ..writeln('-- Generated by tool/import_base44/import.dart')
    ..writeln('-- Apply with the Supabase CLI; re-running is safe.')
    ..writeln();
  for (final name in ['depots.sql', 'routine_tasks.sql', 'trucks.sql']) {
    final f = File('${outDir.path}/$name');
    if (f.existsSync()) {
      combined.writeln('\\i ${f.path}');
    }
  }
  _write(outDir, 'base44.sql', combined.toString());

  stdout.writeln('Import plan written to ${outDir.path}');
  report.forEach((k, v) => stdout.writeln('  $k: $v rows'));
  stdout.writeln(
    'Skipped: sample rows (is_sample = true) and rows with no key.',
  );
}

/// Emits a `psql`-style include file. psql is not assumed to be available, so
/// the combined file is documentation-first; the per-table files are the real
/// payload.
void _write(Directory dir, String name, String content) {
  File('${dir.path}/$name').writeAsStringSync(content);
}

String _expand(String path) => path.startsWith('~')
    ? '${Platform.environment['HOME']}${path.substring(1)}'
    : path;

File? _find(Directory dir, List<String> names) {
  for (final name in names) {
    final f = File('${dir.path}/$name');
    if (f.existsSync()) return f;
  }
  return null;
}

String? _value(List<String> args, String flag) {
  final i = args.indexOf(flag);
  if (i == -1 || i + 1 >= args.length) return null;
  return args[i + 1];
}
